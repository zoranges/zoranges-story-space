function findScrollLayer() {
  const candidates = [...document.querySelectorAll("body *")].filter((element) => {
    const style = getComputedStyle(element);
    return (
      element.scrollHeight > element.clientHeight + 80 &&
      style.overflowY !== "visible" &&
      style.position === "absolute"
    );
  });

  scrollLayer = candidates.sort((a, b) => b.scrollHeight - a.scrollHeight)[0] || null;
  return scrollLayer;
}

function isThreeDAtEnd() {
  const layer = scrollLayer || findScrollLayer();
  if (!layer) return false;
  return layer.scrollTop + layer.clientHeight >= layer.scrollHeight - 12;
}

function isThreeDAtStart() {
  const layer = scrollLayer || findScrollLayer();
  if (!layer) return true;
  return layer.scrollTop <= 12;
}

function setPage(page) {
  currentPage = Math.max(-1, Math.min(TOTAL_PAGES, page));
  document.body.classList.remove("page-rippling");
  document.body.classList.toggle("opening-active", currentPage === -1);

  if (currentPage <= 0) {
    document.body.removeAttribute("data-story-page");
    history.replaceState(null, "", currentPage === -1 ? "#opening" : location.pathname);
  } else {
    document.body.dataset.storyPage = String(currentPage);
    const active = document.querySelector(`.story-page[data-page="${currentPage}"]`);
    history.replaceState(null, "", active ? `#${active.id}` : `#page-${currentPage}`);
    window.requestAnimationFrame(() => {
      document.body.classList.add("page-rippling");
      window.setTimeout(() => document.body.classList.remove("page-rippling"), 1200);
    });
  }

  syncIndicator();
}

function canSwitch() {
  if (pageTurnLocked) return false;
  const now = performance.now();
  if (now - lastSwitchAt < 1400) return false;
  lastSwitchAt = now;
  pageTurnLocked = true;
  window.setTimeout(() => {
    pageTurnLocked = false;
  }, 1400);
  return true;
}

function activePaper() {
  if (currentPage <= 0) return null;
  return document.querySelector(`.story-page[data-page="${currentPage}"] .story-paper`);
}

function syncCue() {
  document.body.classList.toggle("ready-for-story", currentPage === 0 && isThreeDAtEnd());
  document.body.classList.toggle("ready-for-3d", currentPage === -1);
}

function buildIndicator() {
  const indicator = document.querySelector(".page-indicator");
  if (!indicator) return;

  for (let page = 1; page <= TOTAL_PAGES; page += 1) {
    const button = document.createElement("button");
    button.type = "button";
    button.setAttribute("aria-label", `Go to page ${page}`);
    button.addEventListener("click", () => setPage(page));
    indicator.append(button);
  }
}

function syncIndicator() {
  document.querySelectorAll(".page-indicator button").forEach((button, index) => {
    button.classList.toggle("is-active", index + 1 === currentPage);
  });
}

function goNext() {
  if (currentPage === -1) {
    setPage(0);
    return;
  }

  if (currentPage === 0) {
    if (!isThreeDAtEnd()) return;
    setPage(1);
    return;
  }

  setPage(currentPage + 1);
}

function goPrevious() {
  if (currentPage === -1) return;
  if (currentPage === 0) {
    if (isThreeDAtStart()) setPage(-1);
    return;
  }

  setPage(currentPage - 1);
}

window.addEventListener(
  "wheel",
  (event) => {
    if (document.body.classList.contains("reader-open")) {
      event.preventDefault();
      if (Math.abs(event.deltaY) > 8) {
        turnReaderPage(event.deltaY > 0 ? "next" : "prev");
      }
      return;
    }

    syncCue();
    if (!canSwitch()) return;

    if (event.deltaY > 0) {
      const before = currentPage;
      goNext();
      if (currentPage !== before) event.preventDefault();
      return;
    }

    if (event.deltaY < 0) {
      const before = currentPage;
      goPrevious();
      if (currentPage !== before) event.preventDefault();
    }
  },
  { passive: false, capture: true }
);

window.addEventListener(
  "scroll",
  () => {
    syncCue();
  },
  true
);

window.addEventListener("keydown", (event) => {
  if (document.body.classList.contains("reader-open")) {
    if (event.key === "ArrowRight" || event.key === "PageDown") turnReaderPage("next");
    if (event.key === "ArrowLeft" || event.key === "PageUp") turnReaderPage("prev");
    if (event.key === "Escape") closeReader();
    return;
  }

  if (event.key === "PageDown" || event.key === "ArrowDown") {
    goNext();
  }

  if (event.key === "PageUp" || event.key === "ArrowUp") {
    goPrevious();
  }

  if (event.key === "Escape") {
    setPage(0);
  }
});

